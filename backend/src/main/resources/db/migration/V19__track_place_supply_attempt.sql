-- 공용 장소 자동 보충의 재시도 억제를 인스턴스 간에 공유한다.
-- (도메인 가이드 결정 '공용 장소 자동 보충')
--
-- 채울 수 없는 동네(섬처럼 20km 안에 공공기관이 없는 곳, 연동 장애)를 매 조회마다 다시
-- 시도하면 외부 호출이 쌓인다. 시도 시각을 인메모리로 기억하면 인스턴스마다 따로 세어
-- 여러 대로 늘렸을 때 호출이 인스턴스 수만큼 늘어난다. 그래서 동네 행에 남긴다.
--
-- 채우기에 성공하면 장소가 생겨 보충 자체가 다시 돌지 않으므로, 이 값은 실패한 시도를
-- 기억하는 용도다.

ALTER TABLE communities
    ADD COLUMN place_supply_attempted_at DATETIME(6) NULL
        COMMENT '공용 장소 자동 보충을 마지막으로 시도한 UTC 시각. 재시도 간격 판단용';
