-- 위치 인증 기준을 행정동에서 법정동(읍면동)으로 교체한다.
-- (도메인 가이드 결정 '행정동 위치 인증' 갱신)
--
-- 법정동 코드 10자리는 시도(2)+시군구(3)+읍면동(3)+리(2)다. 뒤 2자리를 그대로 쓰면
-- 농촌이 리 단위로 쪼개진다 (양평읍 양근리, 대관령면 차항리). 앞 8자리만 쓰면
-- 도시는 법정동(역삼동), 농촌은 읍면(양평읍)으로 단위가 통일되고
-- VWorld 행정구역 검색의 L4 id와 같은 값이 된다.
--
-- 기존 값은 행정동 코드라 법정동 체계에서 의미가 없다. 잘라 쓸 수도 없어 비운다.
-- 비운 동네는 반경 판정으로만 동작하고, 다시 조회될 때 법정동 코드로 등록된다.
-- 이 기능은 아직 배포되지 않았으므로 운영 데이터 손실은 없다.

UPDATE communities SET region_code = NULL WHERE region_code IS NOT NULL;

ALTER TABLE communities
    MODIFY COLUMN region_code CHAR(8) NULL COMMENT '법정동 코드 앞 8자리(읍면동). 역지오코딩 결과와 비교';
